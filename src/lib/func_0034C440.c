typedef struct { void *src; void *dest; int size; int attr; } DmaC440;
typedef struct { int pending; char pad[8]; int state; char pad2[8]; int cap; void *buf; int ack; char pad3[8]; int dest; } BufC440;
typedef struct { char pad[0x24]; BufC440 *b; } CdC440;
extern char D_004BA7D0[];
extern void FlushCache(int mode);
extern void *memcpy(void *d, const void *s, unsigned int n);
extern unsigned int sceSifSetDma(DmaC440 *d, int n);
extern int sceSifDmaStat(unsigned int id);
extern int printf(const char *fmt, ...);
int sceBInetSend(int a, int b, CdC440 *cd, void *data, int len)
{
    BufC440 *p;
    DmaC440 dma;
    unsigned int id;
    int n;
    if (cd == 0) return -0x200;
    p = cd->b;
    FlushCache(0);
    if (p->state != 0) return p->state != 3 ? 0 : -0x1F5;
    if (p->pending > 0) return 0;
    if (p->pending < 0) return p->pending;
    n = len;
    if (p->cap < n) n = p->cap;
    memcpy(p->buf, data, n);
    FlushCache(0);
    dma.src = p->buf;
    dma.dest = (void *)p->dest;
    dma.size = n;
    dma.attr = 0;
    id = sceSifSetDma(&dma, 1);
    if (id == 0) printf(D_004BA7D0);
    while (sceSifDmaStat(id) >= 0);
    p->pending = n;
    FlushCache(0);
    dma.src = p;
    dma.dest = (void *)p->ack;
    dma.size = 4;
    dma.attr = 0;
    id = sceSifSetDma(&dma, 1);
    if (id == 0) printf(D_004BA7D0);
    while (sceSifDmaStat(id) >= 0);
    return n;
}
