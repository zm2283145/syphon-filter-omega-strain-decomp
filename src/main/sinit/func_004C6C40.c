/* Copies a 4-character tag, zero-filling after the terminator. */
static inline void Tag4Copy(char* d, const char* s) {
    unsigned char end = 0;
    unsigned int i;
    for (i = 0; i < 4; i++) {
        char c = s[i];
        if (!c) end = 1;
        d[i] = end ? (char)0 : c;
    }
}

