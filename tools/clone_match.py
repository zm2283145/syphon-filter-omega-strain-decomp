#!/usr/bin/env python3
"""clone.py - clone/template auto-matcher for the SCUS_972.64 matching decomp.

Finds unmatched functions (glabel blocks in the asm segments asm/*.s) whose
normalised instruction shape equals that of an already matched function (the
retail disassembly of a C unit, asm/<unit>.s), rewrites the template unit's
source for the clone (function name, callees, globals, vtables and - for
"loose" pairs - single differing immediates), runs tools/check_match.py and
keeps only full MATCH results as build/pending/clone/<kind>_<ADDR>.c.

usage (repo root, CW38_DIR / CW50_DIR / CW304_DIR set as for check_match.py):
  .venv\\Scripts\\python.exe tools\\clone_match.py scan
        parse asm, build shapes, write build/clone/groups.json + summary
  .venv\\Scripts\\python.exe tools\\clone_match.py run [--mode strict|loose|all] [-j N]
        generate candidates (work/cand/) and check them; matches go to
        build/pending/clone; results are appended to work/results.json
  .venv\\Scripts\\python.exe tools\\clone_match.py families [--top N]
        list the biggest template-less families of unmatched clones
        (stamping: a hand-matched build/pending/clone/<kind>_<ADDR>.c is a template
        for every unmatched function with the same shape; `scan` + `run` then
        generates the rest of the family, reported as mode "family")
  .venv\\Scripts\\python.exe tools\\clone_match.py report
        print the statistics of results.json

Templates are also taken from build/pending/*/ files (matched but not yet
integrated) with --pending. Re-run `scan` + `run` after each integration
round: newly matched units become templates automatically.
"""
