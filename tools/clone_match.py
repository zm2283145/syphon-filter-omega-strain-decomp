AG = ROOT / "build" / "clone"
WORK = AG / "work"
PEND = ROOT / "build" / "pending" / "clone"
PY = str(ROOT / ".venv" / "Scripts" / "python.exe") if os.name == "nt" else sys.executable
BASE = 0x100000

KIND_OF = {"cwps2-3.0b38": "mw38", "cwps2-3.0b50": "mw50", "cwps2-3.04": "mw304",
           "ee-gcc2.96": "gcc296", "ee-gcc2.96-G0": "gcc296g0", "ee-gcc2.9-991111": "gcc29"}
ALT_KINDS = {"mw38": ["mw50", "mw", "mw304"], "mw50": ["mw38", "mw", "mw304"], "mw": ["mw38", "mw50", "mw304"],
             "mw304": ["mw38", "mw50", "mw"], "gcc296": ["gcc296g0", "gcc29", "gcc"],
             "gcc296g0": ["gcc296", "gcc29", "gcc"], "gcc29": ["gcc296g0", "gcc296", "gcc"],
             "gcc": ["gcc296g0", "gcc296", "gcc29"]}

INS = re.compile(r"\s*/\* ([0-9A-F]+) ([0-9A-F]{8}) ([0-9A-F]{8}) \*/\s+(\S+)\s*(.*?)\s*(?:/\*.*\*/)?\s*$")
RELOC = re.compile(r"%(hi|lo|gp_rel)\(([\w.]+)(?:\s*([+-])\s*(0x[0-9A-Fa-f]+|\d+))?\)")
SYMRE = re.compile(r"(?:func|D|jtbl)_([0-9A-F]{8})$")


# ---------------------------------------------------------------- asm parsing
class Func:
    __slots__ = ("name", "addr", "words", "ops", "mn", "file", "unit", "matched", "handwritten")

    def __init__(self, name, file, unit, matched, handwritten):
        self.name, self.file, self.unit, self.matched, self.handwritten = name, file, unit, matched, handwritten
        self.addr, self.words, self.ops, self.mn = None, [], [], []


def parse_asm_file(path, unit, matched):
    funcs, cur, hw = [], None, False
    try:
        text = path.read_text(errors="replace").splitlines()
    except OSError:   # asm/ is being regenerated by a configure run
        print(f"warning: cannot read {path}", file=sys.stderr)
        return []
    for l in text:
        if l.startswith("/* Handwritten function"):
            hw = True; continue
        if l.startswith(".section"):
            if cur:
                funcs.append(cur); cur = None
            continue
        if l.startswith("glabel "):
            if cur:
                funcs.append(cur)
            cur = Func(l.split()[1], str(path.relative_to(ROOT)), unit, matched, hw); hw = False
            continue
        if l.startswith("endlabel"):
            if cur:
                funcs.append(cur); cur = None
            continue
        if cur is None:
            continue
        m = INS.match(l)
        if m:
            a = int(m.group(2), 16)
            if cur.addr is None:
                cur.addr = a
            w = int(m.group(3), 16)
            w = struct.unpack("<I", struct.pack(">I", w))[0]
            cur.words.append(w); cur.mn.append(m.group(4)); cur.ops.append(m.group(5))
    if cur:
        funcs.append(cur)
    return [f for f in funcs if f.addr is not None and f.words]


def splat_units():
    units, data_units = [], set()
    for l in (ROOT / "config" / "splat.yaml").read_text().splitlines():
        m = re.match(r"\s*- \[(0x[0-9A-Fa-f]+),\s*([\w.]+)(?:,\s*([\w/.]+))?", l)
        if not m:
            continue
        if m.group(2) == "c":
            units.append(m.group(3))
        elif m.group(2) in (".data", ".rodata", ".sdata") and m.group(3):
            data_units.add(m.group(3))
    return units, data_units


def load_names():
    names = {}
    for l in (ROOT / "config" / "symbol_addrs.txt").read_text().splitlines():
        m = re.match(r"\s*(\w+)\s*=\s*0x([0-9A-Fa-f]+)\s*;", l)
        if m:
            names[m.group(1)] = int(m.group(2), 16)
    return names


def unit_kind(unit, overrides):
    if unit in overrides:
        return KIND_OF.get(overrides[unit], "mw")
    return "gcc" if unit.startswith("lib/") else "mw"


def scan_all():
    units, data_units = splat_units()
    overrides = json.loads((ROOT / "config" / "compiler_overrides.json").read_text())
    funcs = []
    for u in units:
        p = ROOT / "asm" / (u + ".s")
        if p.exists() and (ROOT / "src" / (u + ".c")).exists():
            funcs += parse_asm_file(p, u, True)
    for p in sorted((ROOT / "asm").glob("*.s")):
        funcs += parse_asm_file(p, None, False)
    return funcs, units, data_units, overrides


# ---------------------------------------------------------------- shapes
def reloc_of(f, i):
    """('call', sym) / ('hi'|'lo'|'gp_rel', sym, off) / ('jlocal', rel) / None"""
    mn, op = f.mn[i], f.ops[i]
    if mn in ("jal", "j") and not op.startswith("$"):
        tgt = (f.words[i] & 0x3FFFFFF) << 2 | (f.addr & 0xF0000000)
        end = f.addr + 4 * len(f.words)
        if mn == "j" and f.addr <= tgt < end:
            return ("jlocal", tgt - f.addr)
        return ("call", op.split()[0], mn)
    m = RELOC.search(op)
    if m:
        off = 0
        if m.group(4):
            off = int(m.group(4), 0) * (-1 if m.group(3) == "-" else 1)
        return (m.group(1), m.group(2), off)
    return None


def canon_zero(w):
    """'daddu/addu/or rd, $zero, $zero' (load 0) -> 'addiu rd, $zero, 0', so 0-vs-N constants align."""
    if w >> 26 == 0 and (w >> 16) & 0x3FF == 0 and w & 0x7FF in (0x2D, 0x21, 0x25):
        return (9 << 26) | (((w >> 11) & 31) << 16)
    return w


def masked(f, i, loose):
    w = f.words[i]
    r = reloc_of(f, i)
    if r:
        if r[0] == "call":
            return (w & 0xFC000000) | 1
        if r[0] == "jlocal":
            return (w & 0xFC000000) | (r[1] & 0xFFFF) | 0x8000000
        w = w & 0xFFFF0000
        return w
    if loose:
        w = canon_zero(w)
        op = w >> 26
        if op not in (0, 2, 3, 0x10, 0x11, 0x12, 0x13, 0x1C):
            return w & 0xFFFF0000
    return w


def shape(f, loose):
    h = hashlib.sha1()
    for i in range(len(f.words)):
        h.update(struct.pack("<I", masked(f, i, loose)))
    return h.hexdigest()[:20]


# ---------------------------------------------------------------- scan
def groups(db, key):
    """shape -> {'templates': [addr], 'clones': [addr]} for every shape with an unmatched member."""
    g = collections.defaultdict(lambda: {"templates": [], "clones": []})
    for t in db.template_funcs():
        g[shape(t, key)]["templates"].append(t.addr)
    for c in db.targets():
        g[shape(c, key)]["clones"].append(c.addr)
    return {k: v for k, v in g.items() if v["clones"]}


def cmd_scan(args):
    db = DB(use_pending=not getattr(args, "no_pending", False))
    out = {}
    print(f"functions: {len(db.funcs)}  templates: {len(db.tmpl)} "
          f"(pending files {sum(1 for a in db.tmpl if a in db.unmatched)})  "
          f"unmatched targets: {len(db.targets())}")
    for key in ("strict", "loose"):
        g = groups(db, key == "loose")
        out[key] = g
        hit = [v for v in g.values() if v["templates"]]
        fam = sorted((v for v in g.values() if not v["templates"] and len(v["clones"]) >= 2),
                     key=lambda v: -len(v["clones"]))
        print(f"{key}: {len(hit)} shape groups with a template covering {sum(len(v['clones']) for v in hit)} "
              f"unmatched; template-less families: {sum(1 for v in fam if len(v['clones']) >= 3)} of >=3, "
              f"{len(fam)} of >=2 ({sum(len(v['clones']) for v in fam)} functions)")
    (AG / "groups.json").write_text(json.dumps(out, indent=0))

# ---------------------------------------------------------------- templates / pairs
PEND_RE = re.compile(r"(?:([a-z0-9]+)_)?([0-9A-F]{8})\.c$")


def pending_files(exclude_self=True):
    """addr -> [(kind, path)] for every hand-matched file waiting in build/pending/*/."""
    out = {}
    for d in sorted((ROOT / "build" / "pending").iterdir()):
        if not d.is_dir() or (exclude_self and d.name == PEND.name):
            continue
        for p in d.glob("*.c"):
            m = PEND_RE.match(p.name)
            if m:
                out.setdefault(int(m.group(2), 16), []).append((m.group(1) or "gcc", p))
    return out


class DB:
    """All functions (parsed asm) plus template sources."""

    def __init__(self, use_pending=True):
        funcs, units, data_units, overrides = scan_all()
        self.names = load_names()
        self.alias = collections.defaultdict(set)      # addr -> names that may denote it
        for n, a in self.names.items():
            self.alias[a].add(n)
        self.by_addr, self.matched, self.unmatched = {}, {}, {}
        unit_nfuncs = collections.Counter(f.unit for f in funcs if f.matched)
        for f in funcs:
            self.alias[f.addr].add(f.name)
            if f.matched:
                self.matched[f.addr] = f
        for f in funcs:
            if not f.matched and f.addr not in self.matched and not f.handwritten:
                self.unmatched.setdefault(f.addr, f)
        self.funcs = {**self.unmatched, **self.matched}
        self.tmpl = {}   # addr -> dict(src=Path, kind=str, single=bool, origin=str)
        for a, f in self.matched.items():
            self.tmpl[a] = {"src": ROOT / "src" / (f.unit + ".c"), "kind": unit_kind(f.unit, overrides),
                            "single": unit_nfuncs[f.unit] == 1, "origin": f.unit}
        self.add_merged_blocks(unit_nfuncs)
        self.pending = pending_files()
        if use_pending:
            for a, lst in self.pending.items():
                if a in self.unmatched and a not in self.tmpl:
                    kind, p = lst[0]
                    self.tmpl[a] = {"src": p, "kind": kind, "single": True,
                                    "origin": str(p.relative_to(ROOT))}
        mine = {int(PEND_RE.match(p.name).group(2), 16): p for p in PEND.glob("*.c") if PEND_RE.match(p.name)}
        for a, p in mine.items():
            if a in self.unmatched and a not in self.tmpl:
                self.tmpl[a] = {"src": p, "kind": PEND_RE.match(p.name).group(1) or "gcc", "single": True,
                                "origin": str(p.relative_to(ROOT))}
        self.done_elsewhere = set(self.pending)   # already hand-matched by someone: not a target
        self.done_mine = set(mine)

    def add_merged_blocks(self, unit_nfuncs):
        """A unit merged by tools/merge_units.py keeps each original file as one
        block; a block holding one function is a template on its own (the
        declarations it uses from earlier blocks are put in front of it)."""
        import merge_units
        by_unit = collections.defaultdict(list)
        for a, f in self.matched.items():
            if unit_nfuncs[f.unit] > 1:
                by_unit[f.unit].append(a)
        for unit, addrs in by_unit.items():
            src = ROOT / "src" / (unit + ".c")
            if not src.exists() or "merge_units: begin" not in src.read_text(errors="replace"):
                continue
            kind = self.tmpl[addrs[0]]["kind"]
            chunks = merge_units.read_chunks(src, kind)
            labels = [c.addr if c.label.startswith("func_") else None for c in chunks]
            if None in labels:
                continue
            addrs.sort()
            for j, lo in enumerate(labels):
                hi = labels[j + 1] if j + 1 < len(labels) else float("inf")
                inside = [a for a in addrs if lo <= a < hi]
                if inside != [lo]:
                    continue
                text = merge_units.standalone(chunks, j, src.parent, kind in merge_units.MW_KINDS)
                self.tmpl[lo] = dict(self.tmpl[lo], single=True, text=text)

    def targets(self):
        return [f for a, f in sorted(self.unmatched.items())
                if a not in self.done_elsewhere and a not in self.done_mine]

    def template_funcs(self):
        return [self.funcs[a] for a in self.tmpl if a in self.funcs]

    def addr_of(self, name):
        if name in self.names:
            return self.names[name]
        m = SYMRE.match(name)
        return int(m.group(1), 16) if m else None


def find_pairs(db, mode):
    """[(template Func, clone Func, mode)], best template first per clone."""
    key = mode == "loose"
    idx = collections.defaultdict(list)
    for t in db.template_funcs():
        idx[shape(t, key)].append(t)
    out = []
    for c in db.targets():
        ts = [t for t in idx.get(shape(c, key), []) if t.addr != c.addr]
        if mode == "loose" and ts and any(shape(t, False) == shape(c, False) for t in ts):
            continue  # strict pair: handled by the strict pass
        # prefer: single-function units, known compiler (override), no own data, nearest address
        ts.sort(key=lambda t: (not db.tmpl[t.addr]["single"], db.tmpl[t.addr]["kind"] in ("mw", "gcc"),
                               abs(t.addr - c.addr)))
        for t in ts[:4]:
            out.append((t, c, mode))
    return out


# ---------------------------------------------------------------- candidate generation
def s16(v):
    return v - 0x10000 if v & 0x8000 else v


UNSIGNED_IMM = {"andi", "ori", "xori", "lui"}
LOADSTORE = {"lb", "lbu", "lh", "lhu", "lw", "lwu", "ld", "lq", "lwc1", "sb", "sh", "sw", "sd", "sq", "swc1",
             "lwl", "lwr", "swl", "swr", "ldl", "ldr", "sdl", "sdr", "lqc2", "sqc2"}


class Skip(Exception):
    pass


def diff_pair(db, t, c):
    """symbol map {template addr: clone name} and immediate diffs [(mn, tval, cval)]."""
    if len(t.words) != len(c.words):
        raise Skip("length differs")
    smap, imms = {}, []
    for i in range(len(t.words)):
        rt, rc = reloc_of(t, i), reloc_of(c, i)
        if (rt is None) != (rc is None) or (rt and rt[0] != rc[0]):
            raise Skip("relocation kinds differ")
        if rt:
            if rt[0] == "jlocal":
                continue
            ts, cs = rt[1], rc[1]
            if ts.startswith("jtbl_") or cs.startswith("jtbl_"):
                if ts.startswith("jtbl_") != cs.startswith("jtbl_"):
                    raise Skip("jump table vs symbol")
                continue
            if rt[0] != "call" and rt[2] != rc[2]:
                raise Skip(f"reloc offset differs ({ts}+{rt[2]:#x} vs {cs}+{rc[2]:#x})")
            ta = db.addr_of(ts)
            if ta is None:
                raise Skip(f"unknown template symbol {ts}")
            if ta == t.addr and cs != c.name and db.addr_of(cs) != c.addr:
                raise Skip("self reference mismatch")
            prev = smap.get(ta)
            if prev is not None and prev != cs:
                raise Skip(f"inconsistent symbol map {ts}->{prev}/{cs}")
            smap[ta] = cs
            continue
        wt, wc = t.words[i], c.words[i]
        if wt != wc:
            wt, wc = canon_zero(wt), canon_zero(wc)
            if (wt & 0xFFFF0000) != (wc & 0xFFFF0000):
                raise Skip("opcode/register differs")
            mn = "addiu" if wt >> 26 == 9 else t.mn[i]
            if mn in UNSIGNED_IMM:
                imms.append((mn, wt & 0xFFFF, wc & 0xFFFF))
            else:
                imms.append((mn, s16(wt & 0xFFFF), s16(wc & 0xFFFF)))
    smap[t.addr] = c.name
    return smap, imms


DEF_RE = re.compile(r"^(?P<head>[^\n;{}()]*?\b)(?P<name>D_[0-9A-F]{8})(?P<dims>(?:\s*\[[^\]]*\])*)\s*=", re.M)


def split_definition(src, m):
    """end index (after ';') of the top-level definition whose '=' is matched by m"""
    depth, i, q = 0, m.end(), None
    while i < len(src):
        ch = src[i]
        if q:
            if ch == "\\":
                i += 2; continue
            if ch == q:
                q = None
        elif ch in "\"'":
            q = ch
        elif ch in "{([":
            depth += 1
        elif ch in "})]":
            depth -= 1
        elif ch == ";" and depth == 0:
            return i + 1
        i += 1
    return len(src)


def c_string(rom, addr):
    end = rom.index(b"\0", addr - BASE)
    s = rom[addr - BASE:end]
    out = []
    for b in s:
        ch = chr(b)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 32 <= b < 127:
            out.append(ch)
        else:
            out.append({10: "\\n", 13: "\\r", 9: "\\t"}.get(b, f"\\{b:03o}"))
    return '"' + "".join(out) + '"'


def rewrite_data(db, src, smap, rom, regen):
    """Handle data the template defines: regenerate it for the clone (strings, pointer tables)
    when regen, else turn the definition into an extern declaration."""
    out, pos = [], 0
    for m in list(DEF_RE.finditer(src)):
        head = m.group("head")
        if "extern" in head or head.strip().startswith(("#", "//")):
            continue
        ta = int(m.group("name")[2:], 16)
        end = split_definition(src, m)
        body = src[m.end():end]
        cname = smap.get(ta, m.group("name"))
        ca = db.addr_of(cname)
        head2 = re.sub(r"\bstatic\s+", "", head)
        dims = m.group("dims")
        new = None
        if regen and ca is not None and ca != ta:
            if body.strip().startswith('"'):
                new = f"{head}{cname}{dims} = {c_string(rom, ca)};"
            elif re.match(r"\s*\{\s*\(void\s*\*\)", body):
                n = len(re.findall(r"\(void\s*\*\)", body))
                ents = []
                for k in range(n):
                    w, = struct.unpack_from("<I", rom, ca - BASE + 4 * k)
                    nm = None
                    if w:
                        cand = sorted(db.alias.get(w, ()), key=lambda s: (s.startswith(("func_", "D_")), s))
                        nm = cand[0] if cand else None
                        if nm is None:
                            raise Skip(f"pointer {w:#x} in data has no symbol")
                    ents.append(f"(void*){nm}" if nm else "(void*)0x0")
                new = f"{head}{cname}{dims} = {{ {', '.join(ents)} }};"
        if new is None:
            if ca == ta and cname == m.group("name") and ta not in smap:
                continue  # data the clone does not touch: keep as is
            dims_e = re.sub(r"\[[^\]]*\]", "[]", dims, count=1)
            new = f"extern {head2.strip()} {cname}{dims_e};".replace("  ", " ")
            new = re.sub(r"^extern\s+(.*?)\s+(const\s+)?(D_)", r"extern \1 \2\3", new)
        out.append(src[pos:m.start()]); out.append(new); pos = end
    out.append(src[pos:])
    return "".join(out)


NUM = re.compile(r"(?<![\w.])(0[xX][0-9A-Fa-f]+|\d+)([uUlL]*)(?![\w.])")


def apply_imms(src, imms):
    """variants of src with the template literal of each differing immediate replaced by the clone's."""
    if not imms:
        return [src]
    want = {}
    for mn, tv, cv in imms:
        for a, b in [(tv, cv)] + ([(tv << 16, cv << 16)] if mn == "lui" else []):
            if want.get(a, b) != b:
                raise Skip(f"immediate {a:#x} maps to two values")
            want[a] = b
    hits = []
    for m in NUM.finditer(src):
        v = int(m.group(1), 0)
        for tv, cv in want.items():
            if v == tv:
                hits.append((m, tv, cv))
            elif tv < 0 and v == -tv:      # written as "-N" / "x - N"
                hits.append((m, tv, -cv))
    found = {h[1] for h in hits}
    for mn, tv, cv in imms:
        if tv not in found and not (mn == "lui" and (tv << 16) in found):
            raise Skip(f"immediate {tv:#x} ({mn}) not a literal in the source")

    def fmt(orig, v):
        h = orig.lower().startswith("0x")
        return ("-" if v < 0 else "") + (f"0x{abs(v):X}" if h else str(abs(v)))

    def build(sel):
        out, pos = [], 0
        for m, tv, newv in sorted(sel, key=lambda h: h[0].start()):
            out.append(src[pos:m.start()]); out.append(fmt(m.group(1), newv) + m.group(2)); pos = m.end()
        out.append(src[pos:])
        return "".join(out)

    variants = [build(hits)]
    # struct padding: "char padD0[0xE0 - 0xD0]" - shift the other array-size literals piecewise
    ls = sorted({(tv, cv) for mn, tv, cv in imms if mn in LOADSTORE and tv >= 0})
    if ls:
        hit_pos = {h[0].start() for h in hits}
        extra = []
        for m in NUM.finditer(src):
            if m.start() in hit_pos:
                continue
            v = int(m.group(1), 0)
            lb, rb = src.rfind("[", 0, m.start()), src.rfind("]", 0, m.start())
            if lb <= rb or "\n" in src[lb:m.start()]:
                continue
            below = [(tv, cv) for tv, cv in ls if tv <= v]
            if below and v - below[-1][0] <= 16:
                tv, cv = below[-1]
                extra.append((m, tv, v + cv - tv))
        if extra:
            variants.insert(0, build(hits + extra))
    if 1 < len(hits) <= 6:
        # only some of the equal literals may be the differing ones
        byval = collections.defaultdict(list)
        for h in hits:
            byval[h[1]].append(h)
        for tv, hs in byval.items():
            if len(hs) > 1:
                rest = [h for h in hits if h[1] != tv]
                for h in hs:
                    variants.append(build(rest + [h]))
    seen, res = set(), []
    for v in variants:
        if v not in seen:
            seen.add(v); res.append(v)
    return res[:8]

def rename(src, db, smap):
    """replace every name of a template address by the clone's name (one simultaneous pass)."""
    repl, missing = {}, []
    for ta, cname in smap.items():
        names = set(db.alias.get(ta, ())) | {f"func_{ta:08X}", f"D_{ta:08X}"}
        if cname in names:
            continue
        present = [n for n in names if re.search(r"\b" + re.escape(n) + r"\b", src)]
        if not present:
            missing.append((sorted(names)[0], cname))
        for n in names:
            repl[n] = cname
    if repl:
        rx = re.compile(r"\b(" + "|".join(sorted(map(re.escape, repl), key=len, reverse=True)) + r")\b")
        src = rx.sub(lambda m: repl[m.group(1)], src)
    return src, missing


def generate(db, t, c, mode, rom):
    """list of (variant tag, C text) for clone c from template t."""
    info = db.tmpl[t.addr]
    if not info["single"]:
        raise Skip("template unit has several functions")
    smap, imms = diff_pair(db, t, c)
    if mode == "strict" and imms:
        raise Skip("immediates differ")
    base = info["text"] if "text" in info else info["src"].read_text(errors="replace")
    outs = []
    for regen in (True, False):
        s = rewrite_data(db, base, smap, rom, regen)
        s, missing = rename(s, db, smap)
        if missing:
            # names the template takes from a header: redirect them with a macro
            defs = "".join(f"#define {o} {n}\n" for o, n in missing)
            s = defs + s
        for k, v in enumerate(apply_imms(s, imms)):
            outs.append((("data" if regen else "ext") + (f"i{k}" if imms else ""), v))
    seen, res = set(), []
    for tag, v in outs:
        if v not in seen:
            seen.add(v); res.append((tag, v))
    return res


