def check(path, kinds):
    r = subprocess.run([PY, str(ROOT / "tools" / "check_match.py"), str(path), "-c", ",".join(kinds), "--json"],
                       capture_output=True, text=True, cwd=ROOT, env=check_env())
    try:
        return json.loads(r.stdout.strip().splitlines()[-1])
    except Exception:
        return {"_error": (r.stdout + r.stderr)[-2000:]}


def verdict(rep, kind, fname):
    """('MATCH'|category, detail) for one compiler's result."""
    if "_error" in rep:
        return "TOOL_ERROR", rep["_error"][-300:]
    r = rep.get(kind) if isinstance(rep, dict) else None
    if r is None:
        # tolerate other report layouts: {"results": {kind: ...}}
        r = (rep.get("results") or {}).get(kind) if isinstance(rep, dict) else None
    if r is None:
        return "TOOL_ERROR", json.dumps(rep)[:300]
    if r.get("error"):
        return "COMPILE_ERROR", r["error"][-300:]
    fs = r.get("functions", [])
    if len(fs) != 1:
        return "NOT_ONE_FUNCTION", ",".join(f["name"] for f in fs)
    f = fs[0]
    if f["name"] != fname:
        return "WRONG_NAME", f["name"]
    if f["result"] != "MATCH":
        return "DIFF", f["result"]
    und = [u for u in r.get("undefined", []) if not u.startswith("__dl__FPv")]
    if und:
        return "UNDEF", "; ".join(und)
    bad = [d for d in r.get("data", []) if d.get("result") != "MATCH"]
    if bad:
        return "DATA_DIFF", "; ".join(f"{d.get('section')} {d.get('result')}" for d in bad)
    return "MATCH", ""


def results_load():
    p = WORK / "results.json"
    return json.loads(p.read_text()) if p.exists() else []


def results_save(res):
    (WORK / "results.json").write_text(json.dumps(res, indent=1))


def try_candidates(job):
    """job: dict(clone, cname, template, kind, variants=[(tag, text)], mode). Returns result dict."""
    cand = WORK / "cand"
    cand.mkdir(parents=True, exist_ok=True)
    kinds = [job["kind"]] + [k for k in ALT_KINDS.get(job["kind"], []) if k != job["kind"]]
    best = None
    order = {"MATCH": 0, "DATA_DIFF": 1, "UNDEF": 2, "DIFF": 3, "NOT_ONE_FUNCTION": 4, "WRONG_NAME": 5,
             "COMPILE_ERROR": 6, "TOOL_ERROR": 7}
    for tag, text in job["variants"]:
        p = cand / f"{job['mode']}_{job['clone']:08X}_{job['template']:08X}_{tag}.c"
        p.write_text(text)
        for group in ([kinds[0]], kinds[1:]):
            rep = check(p, group)
            for k in group:
                v, d = verdict(rep, k, job["cname"])
                if best is None or order[v] < order[best["status"]]:
                    best = {"status": v, "detail": d, "kind": k, "file": str(p.relative_to(ROOT)), "tag": tag}
                if v == "MATCH":
                    break
            if best["status"] == "MATCH" or best["status"] in ("COMPILE_ERROR",) and group == [kinds[0]]:
                break
        if best["status"] == "MATCH":
            break
    if best["status"] == "MATCH":
        dst = PEND / f"{best['kind']}_{job['clone']:08X}.c"
        shutil.copyfile(ROOT / best["file"], dst)
        rep = check(dst, [best["kind"]])
        v, d = verdict(rep, best["kind"], job["cname"])
        if v != "MATCH":
            dst.unlink()
            best = {**best, "status": v, "detail": "final recheck: " + d}
        else:
            best["pending"] = str(dst.relative_to(ROOT))
    return {**{k: job[k] for k in ("clone", "cname", "template", "mode")}, "tname": job["tname"], **best}


def cmd_run(args):
    db = DB(use_pending=not args.no_pending)
    rom = (ROOT / "build" / "orig" / "SCUS_972.64.rom").read_bytes()
    modes = ["strict", "loose"] if args.mode == "all" else [args.mode]
    res = results_load()
    done = {(r["clone"], r["template"], r["mode"]) for r in res} if not args.force else set()
    for mode in modes:
        pairs = find_pairs(db, mode)
        if args.only:
            only = {int(x, 16) for x in args.only.split(",")}
            pairs = [p for p in pairs if p[1].addr in only]
        jobs, matched_now = [], set()
        for t, c, md in pairs:
            if Path(db.tmpl[t.addr]["origin"]).parts[:3] == ("build", "pending", PEND.name):
                md = "family"   # stamped from one hand-matched family member
            if (c.addr, t.addr, md) in done:
                continue
            base = {"clone": c.addr, "cname": c.name, "template": t.addr, "tname": t.name, "mode": md}
            try:
                variants = generate(db, t, c, md, rom)
            except Skip as e:
                res.append({**base, "status": "SKIP", "detail": str(e)}); continue
            except Exception as e:  # keep going on odd templates
                res.append({**base, "status": "GEN_ERROR", "detail": repr(e)[:300]}); continue
            jobs.append({**base, "kind": db.tmpl[t.addr]["kind"], "variants": variants})
        print(f"{mode}: {len(pairs)} pairs, {len(jobs)} candidate jobs")
        # one clone at a time per worker: stop trying templates for a clone once it matched
        byclone = collections.defaultdict(list)
        for j in jobs:
            byclone[j["clone"]].append(j)

        def work(js):
            out = []
            for j in js:
                r = try_candidates(j)
                out.append(r)
                if r["status"] == "MATCH":
                    break
            return out
        with cf.ThreadPoolExecutor(max_workers=args.jobs) as ex:
            for out in ex.map(work, byclone.values()):
                for r in out:
                    k = (r["clone"], r["template"], r["mode"])
                    res = [x for x in res if (x["clone"], x["template"], x["mode"]) != k]
                    res.append(r)
                    print(f"  {r['mode']} {r['clone']:08X} {r['cname']} <- {r['tname']}: {r['status']} "
                          f"{r.get('kind', '')} {r.get('detail', '')[:120]}")
                results_save(res)
    results_save(res)
    cmd_report(args)


def cmd_families(args):
    """Biggest template-less families (from groups.json of the last scan), largest first."""
    db = DB(use_pending=True)
    g = json.loads((AG / "groups.json").read_text())
    seen, rows = set(), []
    for key in ("strict", "loose"):
        for v in g[key].values():
            cl = tuple(sorted(a for a in v["clones"] if a not in db.tmpl))
            if v["templates"] or len(cl) < 2 or cl in seen:
                continue
            seen.add(cl)
            n = len(db.funcs[cl[0]].words)
            rows.append((len(cl), n, key, [db.funcs[a].name for a in cl]))
    rows.sort(key=lambda r: (-r[0], -r[0] * r[1]))
    print(f"{len(rows)} template-less families (members x instructions):")
    for cnt, n, key, names in rows[:args.top]:
        print(f"  {cnt:3d} x {n:4d}  {key:6s} {', '.join(names[:6])}{' ...' if len(names) > 6 else ''}")
    print("hand-match one member, save it as build/pending/clone/<kind>_<ADDR>.c and re-run "
          "`scan` + `run`: it is then used as a template for the rest (mode 'family').")


def cmd_report(args):
    res = results_load()
    print("\n== results ==")
    for mode in ("strict", "loose", "family", "near"):
        rs = [r for r in res if r["mode"] == mode]
        if not rs:
            continue
        clones = {r["clone"] for r in rs}
        m = {r["clone"] for r in rs if r["status"] == "MATCH"}
        gen = [r for r in rs if r["status"] not in ("SKIP", "GEN_ERROR")]
        print(f"{mode}: pairs {len(rs)}, clones {len(clones)}, candidates generated {len(gen)}, MATCH {len(m)}")
        cat = collections.Counter()
        for c in clones - m:
            best = sorted((r for r in rs if r["clone"] == c), key=lambda r: r["status"] == "SKIP")[0]
            cat[best["status"] + (": " + best["detail"].split("(")[0][:40] if best["status"] == "SKIP" else "")] += 1
        for k, v in cat.most_common():
            print(f"   {v:4d}  {k}")
    print("matched files:", ", ".join(sorted(p.name for p in PEND.glob("*.c"))))


