#!/usr/bin/env python3
"""Keep hand-written assembly units as source.

config/handwritten.txt lists asm subsegments (splat.yaml ROM starts) whose
functions are all hand-written. For each, this writes src/asm/<VRAM>.s from
splat's disassembly asm/<unit>.s: the same instructions without the
`nonmatching` markers and the offset/address/bytes comments. configure.py
assembles it as the unit's base object (the one that is linked) and keeps
splat's file as the objdiff target, so the build's SHA-256 check and the
report both verify it.

    python tools/handwritten.py           # (re)write src/asm/*.s for listed units
    python tools/handwritten.py --check   # list units whose source is missing
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIST = ROOT / "config" / "handwritten.txt"
SEG_VRAM = 0x100000
PREFIX = re.compile(r"^(\s*)/\* [0-9A-F]+ [0-9A-F]{8} [0-9A-F]{8} \*/\s*")


def units():
    out = []
    if LIST.exists():
        for line in LIST.read_text().splitlines():
            line = line.split("#", 1)[0].strip()
            if line:
                out.append(int(line, 0))
    return out


def source_path(start):
    return Path("src") / "asm" / f"{start + SEG_VRAM:06X}.s"


def asm_path(start, name=None):
    return Path("asm") / ((name or f"{start:X}") + ".s")


def convert(text):
    out = []
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("nonmatching ") or s.startswith("/* Generated by spimdisasm"):
            continue
        out.append(PREFIX.sub(r"\1", line).rstrip())
    while out and not out[-1]:
        out.pop()
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    missing = 0
    for start in units():
        dst = ROOT / source_path(start)
        if a.check:
            if not dst.exists():
                print(f"missing {dst.relative_to(ROOT)}"); missing += 1
            continue
        src = ROOT / asm_path(start)
        if not src.exists():
            print(f"no {src.relative_to(ROOT)} (run configure.py --elf first)"); missing += 1
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(convert(src.read_text()))
        print(f"wrote {dst.relative_to(ROOT)}")
    sys.exit(1 if missing else 0)


if __name__ == "__main__":
    main()
